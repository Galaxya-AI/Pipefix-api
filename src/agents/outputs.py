"""Structured outputs returned by the agents.

Every agent ends its work by calling a finish tool. The arguments of that
call are validated against a pydantic model: `AgentOutput` holds what all
outputs share, and each agent defines a subclass with its own fields and
rules (e.g. `DiagnosisOutput` in `diagnostic_agent.py`).
"""

from __future__ import annotations

from typing import Any

from pydantic import BaseModel, ConfigDict, Field


class AgentOutput(BaseModel):
    """Base class of every structured agent output.

    Parameters
    ----------
    summary : str
        Short conclusion of the agent (one or two sentences).

    Raises
    ------
    pydantic.ValidationError
        If the LLM's answer is missing a field, has a wrong type or adds an unknown key.

    Notes
    -----
    - Outputs are immutable (`frozen=True`): once validated, no code can change them.
    - Unknown keys are refused (`extra="forbid"`): if the LLM invents a field,
      validation fails and the error is sent back to the LLM.
    """

    model_config = ConfigDict(frozen=True, extra="forbid", str_strip_whitespace=True)

    summary: str = Field(..., description="Short conclusion of the agent.")

    @classmethod
    def tool_schema(cls) -> dict[str, Any]:
        """Return the JSON schema used as the parameters of the finish tool.

        Returns
        -------
        dict[str, Any]
            JSON schema generated by pydantic from the model fields.
        """
        return cls.model_json_schema()
